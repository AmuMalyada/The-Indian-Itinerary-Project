"""
02_profile.py
-------------
Data profiling: schema, dtypes, null counts, duplicate counts, cardinality.
Writes docs/DATASET_UNDERSTANDING.md so profiling results are never "lost in
a notebook nobody re-runs" — they live in version-controlled documentation.
"""
import json
import pandas as pd
from common import INTERMEDIATE_DIR, DOCS_DIR, get_logger

log = get_logger("02_profile")

DATASETS = [
    "top_indian_places",
    "temperature_data",
    "sim_destinations",
    "sim_reviews",
    "sim_user_history",
    "sim_users",
]

DESCRIPTIONS = {
    "top_indian_places": "Real-world catalogue of 325 tourist attractions across India "
        "(monuments, temples, forts, parks...) with ratings, fees, and visit metadata. "
        "Source: Kaggle 'Top Indian Places to Visit'.",
    "temperature_data": "Real monthly max/min temperature (°C) for 264 Indian locations. "
        "Source: Kaggle India climate dataset. Joins to attractions on city/location name "
        "(~64 of 214 attraction cities match; see coverage note below).",
    "sim_destinations": "SYNTHETIC practice dataset: 1,000 generated destinations across "
        "only 5 states and 5 fixed types (200 each), with randomly generated Popularity "
        "scores. Does NOT represent real destinations 1:1 with top_indian_places "
        "(only 1 accidental name overlap). Useful for recommender-system / ML practice, "
        "not for factual travel claims.",
    "sim_reviews": "SYNTHETIC reviews linked to sim_destinations/sim_users by generated IDs.",
    "sim_user_history": "SYNTHETIC user visit history linked to sim_destinations/sim_users.",
    "sim_users": "SYNTHETIC user profiles with fake @example.com emails and randomly "
        "assigned preferences.",
}


def profile_dataframe(name: str, df: pd.DataFrame) -> dict:
    return {
        "name": name,
        "rows": int(df.shape[0]),
        "cols": int(df.shape[1]),
        "columns": {
            col: {
                "dtype": str(df[col].dtype),
                "nulls": int(df[col].isna().sum()),
                "null_pct": round(float(df[col].isna().mean()) * 100, 2),
                "unique": int(df[col].nunique(dropna=True)),
            }
            for col in df.columns
        },
        "duplicate_rows": int(df.duplicated().sum()),
    }


def run() -> dict:
    profiles = {}
    for key in DATASETS:
        df = pd.read_parquet(INTERMEDIATE_DIR / "01_ingested" / f"{key}.parquet") \
            if (INTERMEDIATE_DIR / "01_ingested" / f"{key}.parquet").exists() \
            else pd.read_csv(INTERMEDIATE_DIR / "01_ingested" / f"{key}.csv")
        p = profile_dataframe(key, df)
        profiles[key] = p
        log.info(f"{key}: {p['rows']} rows, {p['duplicate_rows']} dup rows")

    with open(INTERMEDIATE_DIR / "profile_report.json", "w") as f:
        json.dump(profiles, f, indent=2)

    write_markdown(profiles)
    return profiles


def write_markdown(profiles: dict) -> None:
    lines = [
        "# Dataset Understanding\n",
        "_Generated by `scripts/02_profile.py`. Phase 1 deliverable: understand every",
        "dataset before writing any transformation logic._\n",
        "## Summary\n",
        "This project draws on **two unrelated data domains** packaged together on Kaggle:\n",
        "1. **Real attraction + climate data** (`top_indian_places`, `temperature_data`) —",
        "   factual, usable for genuine travel-planning analytics.",
        "2. **Synthetic user-engagement data** (`sim_destinations`, `sim_reviews`,",
        "   `sim_user_history`, `sim_users`) — generated/mock data, useful for practicing",
        "   recommendation-system and ML workflows, but **not factual** and not the same",
        "   entities as domain 1 (see coverage note below). This project keeps the two",
        "   domains in clearly separated, honestly-labeled tables rather than faking a",
        "   1:1 merge between them.\n",
    ]
    for key in DATASETS:
        p = profiles[key]
        lines.append(f"## `{key}`\n")
        lines.append(DESCRIPTIONS[key] + "\n")
        lines.append(f"- Rows: **{p['rows']}**, Columns: **{p['cols']}**, Duplicate rows: **{p['duplicate_rows']}**\n")
        lines.append("| Column | dtype | null % | unique values |")
        lines.append("|---|---|---|---|")
        for col, meta in p["columns"].items():
            lines.append(f"| {col} | {meta['dtype']} | {meta['null_pct']}% | {meta['unique']} |")
        lines.append("")

    lines.append("## Cross-dataset coverage note\n")
    lines.append(
        "- `top_indian_places.City` vs `temperature_data.location`: **64 of 214** unique "
        "cities in the attractions table have a matching climate record (exact, "
        "case-insensitive name match). The remaining cities keep `NULL` climate fields "
        "rather than an invented average — this is documented, not silently dropped.\n"
    )
    lines.append(
        "- `sim_destinations` vs `top_indian_places`: only 1 accidental name collision "
        "across 1,000 vs 325 rows, and `sim_destinations` only covers 5 states. The two "
        "are **not** joined as if they were the same entity."
    )

    with open(DOCS_DIR / "DATASET_UNDERSTANDING.md", "w") as f:
        f.write("\n".join(lines))
    log.info("Wrote docs/DATASET_UNDERSTANDING.md")


if __name__ == "__main__":
    run()
